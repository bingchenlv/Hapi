import type { ApiSessionClient } from '@/api/apiSession';
import { record, string } from './gateway';

type Answers = Record<string, string[] | { answers: string[] }>;
type Question = { id: string; question: string; options: Array<{ label: string; description: string }>; isOther: boolean };
type Pending = { threadId: string; callId: string; questions: Question[]; submitted: boolean };

export function asyncQuestionId(threadId: string, itemId: string): string {
    return `codex-async:${threadId}:${itemId}`;
}

/** Codex 0.160 publishes async questions as agentMessage.questions, NOT a
 * requestUserInput server request. Answers are ordinary user messages. Reuse
 * HAPI's question UI, but never respond to a nonexistent JSON-RPC request. */
export class SharedCodexAsyncQuestions {
    private readonly pending = new Map<string, Pending>();
    private readonly retired = new Set<string>();
    constructor(private readonly session: ApiSessionClient,
        private readonly submit: (threadId: string, id: string, text: string) => Promise<void>) {}

    private send(pending: Pending, output?: unknown): void {
        const id = `${pending.callId}:${output === undefined ? 'start' : 'result'}`;
        const message = output === undefined
            ? { type: 'tool-call', name: 'request_user_input', callId: pending.callId,
                input: { questions: pending.questions, isBlocking: false, async: true }, id }
            : { type: 'tool-call-result', callId: pending.callId, output, is_error: false, id };
        const parent = this.session.getMetadata()?.codexSessionId;
        this.session.sendAgentMessage(parent && parent !== pending.threadId ? {
            type: 'agent-run-trace', agentId: pending.threadId, cardId: `codex-agent:${pending.threadId}`,
            message, id, scope: { role: 'child', threadId: pending.threadId, parentThreadId: parent }, scope_role: 'child'
        } : message, id);
    }

    private finish(pending: Pending, status: 'resolved' | 'canceled'): void {
        this.pending.delete(pending.callId);
        this.retired.add(pending.callId);
        this.send(pending, { status });
        this.session.updateAgentState(state => {
            const requests = { ...state.requests };
            const prior = requests[pending.callId]; delete requests[pending.callId];
            return { ...state, requests, completedRequests: { ...state.completedRequests,
                ...(prior ? { [pending.callId]: { ...prior, status, completedAt: Date.now() } } : {}) } };
        });
    }

    observe(method: string, params: unknown, historyIds?: Set<string>): void {
        if (method !== 'item/completed') return;
        const p = record(params); const item = record(p.item);
        const threadId = string(p.threadId); const itemId = string(item.id);
        if (!threadId || !itemId) return;
        if (item.type === 'userMessage') {
            // A new user turn supersedes optional clarification cards. A reply
            // generated by this card is distinguishable by its stable clientId.
            for (const pending of [...this.pending.values()]) {
                if (pending.threadId === threadId && (!historyIds || historyIds.has(pending.callId))) this.finish(pending,
                    item.clientId === `${pending.callId}:answer` ? 'resolved' : 'canceled');
            }
            return;
        }
        if (item.type !== 'agentMessage' || !Array.isArray(item.questions)) return;
        const callId = asyncQuestionId(threadId, itemId);
        historyIds?.add(callId);
        if (this.pending.has(callId) || this.retired.has(callId)) return;
        const questions: Question[] = [];
        for (const [index, raw] of item.questions.entries()) {
            const question = record(raw); const title = string(question.title)?.trim();
            if (!title) continue;
            const options = Array.isArray(question.options) ? question.options
                .filter((option): option is string => typeof option === 'string' && Boolean(option.trim()))
                .map(label => ({ label, description: '' })) : [];
            questions.push({ id: `question_${index}`, question: title, options, isOther: options.length > 0 });
        }
        if (!questions.length) return;
        const pending: Pending = { threadId, callId, questions, submitted: false };
        this.pending.set(callId, pending);
        this.send(pending);
        this.session.updateAgentState(state => {
            // Cold bind cancels stale worker requests. Native history is the
            // authority for reopening an unanswered async question; Web gives
            // completedRequests precedence over requests with the same ID.
            const completedRequests = { ...state.completedRequests }; delete completedRequests[callId];
            return { ...state, completedRequests, requests: { ...state.requests,
                [callId]: { tool: 'request_user_input', toolCallId: callId,
                    arguments: { questions, isBlocking: false, async: true }, createdAt: Date.now() } } };
        });
    }

    history(thread: unknown): void {
        const value = record(thread); const threadId = string(value.id);
        if (!threadId || !Array.isArray(value.turns)) return;
        const historyIds = new Set<string>();
        for (const raw of value.turns) {
            const turn = record(raw);
            if (!Array.isArray(turn.items)) continue;
            for (const item of turn.items) {
                // Async question items are complete at delivery even while
                // their originating turn continues doing independent work.
                if (record(item).type === 'userMessage' || Array.isArray(record(item).questions)) {
                    this.observe('item/completed', { threadId, turnId: turn.id, item }, historyIds);
                }
            }
        }
    }

    has(id: string): boolean { return this.pending.has(id); }

    async reply(reply: { id: string; approved: boolean; answers?: Answers }): Promise<void> {
        const pending = this.pending.get(reply.id);
        if (!pending || pending.submitted) throw new Error('Question already resolved or submitted');
        if (!reply.approved) throw new Error('Answer this optional question or continue in the conversation');
        const lines: string[] = [];
        for (const question of pending.questions) {
            const raw = reply.answers?.[question.id];
            const answers = Array.isArray(raw) ? raw : raw?.answers;
            if (!answers?.some(answer => answer.trim())) throw new Error(`Missing answer: ${question.id}`);
            lines.push(`${question.question}\n${answers.join('\n')}`);
        }
        pending.submitted = true;
        try { await this.submit(pending.threadId, `${pending.callId}:answer`, lines.join('\n\n')); }
        catch (error) { pending.submitted = false; throw error; }
        // Queue acceptance is not native consumption. The userMessage event
        // (also replayable after reconnect) settles the card.
    }

    close(): void {
        const ids = new Set(this.pending.keys());
        this.pending.clear();
        this.session.updateAgentState(state => ({ ...state,
            requests: Object.fromEntries(Object.entries(state.requests ?? {}).filter(([id]) => !ids.has(id))) }));
    }
}
